def abbreviate(type_name : str):
    """
    Return an abbreviation of an underscore-separated type name using initial letters.

    Args:
        type_name (str): Underscore-separated type name, e.g. 'EVENT_TRADE'.

    Returns:
        str: Concatenated initials, e.g. 'ET'.
    """
    return ''.join([s[0] for s in type_name.split('_')])
class FinanceEvent(SimulationEvent):
    """
    Base class for representing market events occurring in the simulation.
    """            
    @classmethod
    def from_json(self, json : dict):
        """
        Method to transform agent event messages generated by simulator to the format required by the MarketSimulationStateUpdate synapse.
        """
        t = json['y'] if 'y' in json else json['type']
        match t:
            case "EVENT_SIMULATION_START":
                return SimulationStartEvent.from_json(json)
            case "ESS":
                return SimulationStartEvent.model_construct(**json)
            case "RESPONSE_DISTRIBUTED_PLACE_ORDER_LIMIT" | "ERROR_RESPONSE_DISTRIBUTED_PLACE_ORDER_LIMIT":
                return LimitOrderPlacementEvent.from_json(json)
            case "RDPOL" | "ERDPOL":
                return LimitOrderPlacementEvent.model_construct(**json)
            case "RESPONSE_DISTRIBUTED_PLACE_ORDER_MARKET" | "ERROR_RESPONSE_DISTRIBUTED_PLACE_ORDER_MARKET":
                return MarketOrderPlacementEvent.from_json(json)
            case "RDPOM" | "ERDPOM":
                json['r'] = OrderCurrency(json['r'])
                return MarketOrderPlacementEvent.model_construct(**json)
            case "EVENT_TRADE":
                return TradeEvent.from_json(json)
            case "ET":
                return TradeEvent.model_construct(**json)
            case "RESPONSE_DISTRIBUTED_CANCEL_ORDERS" | "ERROR_RESPONSE_DISTRIBUTED_CANCEL_ORDERS":
                return OrderCancellationsEvent.from_json(json)
            # model_construct skips validation, which is what the abbreviated wire form wants for
            # scalars but leaves a container's items as raw dicts. The dispatcher hands those items to
            # the miner's handler one at a time, and a handler reads `cancellation.orderId`, so the items
            # have to be events too.
            case "RDCO" | "ERDCO":
                _ev = OrderCancellationsEvent.model_construct(**json)
                _ev.c = [OrderCancellationEvent.model_construct(**_i) if isinstance(_i, dict) else _i
                         for _i in (_ev.c or [])]
                return _ev
            case "RESPONSE_DISTRIBUTED_CLOSE_POSITIONS" | "ERROR_RESPONSE_DISTRIBUTED_CLOSE_POSITIONS":
                return ClosePositionsEvent.from_json(json)
            case "RDCP" | "ERDCP":
                _ev = ClosePositionsEvent.model_construct(**json)
                _ev.o = [ClosePositionEvent.model_construct(**_i) if isinstance(_i, dict) else _i
                         for _i in (_ev.o or [])]
                return _ev
            case "RESPONSE_DISTRIBUTED_RESET_AGENT" | "ERROR_RESPONSE_DISTRIBUTED_RESET_AGENT":
                return ResetAgentsEvent.from_json(json)
            case "RDRA" | "ERDRA":
                return ResetAgentsEvent.model_construct(**json)
            case "EVENT_SIMULATION_END":
                return SimulationEndEvent.from_json(json)
            case "ESE":
                return SimulationEndEvent.model_construct(**json)

